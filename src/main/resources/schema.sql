CREATE TABLE IF NOT EXISTS PUBLIC."user" (
	id BIGINT NOT NULL AUTO_INCREMENT,
	login varchar NOT NULL,
	name varchar NOT NULL,
	birthday DATE,
	email varchar NOT NULL,
	CONSTRAINT user_pk PRIMARY KEY (ID),
	CONSTRAINT user_unique UNIQUE (LOGIN)
);


CREATE TABLE IF NOT EXISTS PUBLIC."mpa" (
	id BIGINT NOT NULL AUTO_INCREMENT,
	name varchar NOT NULL,
	CONSTRAINT MPA_PK PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS PUBLIC."director" (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR NOT NULL,
    CONSTRAINT DIRECTOR_PK PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS PUBLIC."film" (
	id BIGINT NOT NULL AUTO_INCREMENT,
	name varchar NOT NULL,
	description varchar,
	release_date DATE NOT NULL,
	duration BIGINT,
	mpa_id INTEGER,
	CONSTRAINT film_pk PRIMARY KEY (ID),
	CONSTRAINT MPA_MPA_ID_FK FOREIGN KEY (mpa_id) REFERENCES PUBLIC."mpa"(ID)
);

CREATE TABLE IF NOT EXISTS PUBLIC."film_director" (
    film_id BIGINT NOT NULL,
    director_id BIGINT NOT NULL,
    CONSTRAINT pk_film_director PRIMARY KEY (film_id, director_id),
    CONSTRAINT fk_film_director_film_id FOREIGN KEY (film_id) REFERENCES PUBLIC."film"(id) ON DELETE CASCADE,
    CONSTRAINT fk_film_director_director_id FOREIGN KEY (director_id) REFERENCES PUBLIC."director"(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS PUBLIC."genre" (
	id BIGINT NOT NULL AUTO_INCREMENT,
	name varchar NOT NULL,
	CONSTRAINT GENRE_PK PRIMARY KEY (ID)
);


CREATE TABLE IF NOT EXISTS PUBLIC."user_friend" (
	user_id BIGINT NOT NULL,
	friend_id BIGINT NOT NULL,
	is_accepted BOOLEAN DEFAULT FALSE NOT NULL,
	CONSTRAINT USER_FRIEND_PK PRIMARY KEY (FRIEND_ID,USER_ID),
	CONSTRAINT USER_FRIEND_USER_FK_1 FOREIGN KEY (USER_ID) REFERENCES PUBLIC."user"(ID),
	CONSTRAINT USER_FRIEND_USER_FK_2 FOREIGN KEY (FRIEND_ID) REFERENCES PUBLIC."user"(ID)
);


CREATE TABLE IF NOT EXISTS PUBLIC."film_genre" (
	film_id BIGINT NOT NULL,
	genre_id BIGINT NOT NULL,
	CONSTRAINT FILM_GENRE_PK PRIMARY KEY (FILM_ID,GENRE_ID),
	CONSTRAINT FILM_GENRE_FILM_FK FOREIGN KEY (FILM_ID) REFERENCES PUBLIC."film"(ID),
	CONSTRAINT FILM_GENRE_GENRE_FK FOREIGN KEY (GENRE_ID) REFERENCES PUBLIC."genre"(ID)
);

CREATE TABLE IF NOT EXISTS PUBLIC."user_film_like" (
	film_id BIGINT NOT NULL,
	user_id BIGINT NOT NULL,
	CONSTRAINT USER_FILM_LIKE_PK PRIMARY KEY (FILM_ID,USER_ID),
	CONSTRAINT USER_FILM_LIKE_FILM_FK FOREIGN KEY (FILM_ID) REFERENCES PUBLIC."film"(ID),
	CONSTRAINT USER_FILM_LIKE_USER_FK FOREIGN KEY (USER_ID) REFERENCES PUBLIC."user"(ID)
);

CREATE TABLE IF NOT EXISTS PUBLIC."review" (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id BIGINT NOT NULL REFERENCES PUBLIC."user"(id) ON DELETE CASCADE,
    film_id BIGINT NOT NULL REFERENCES PUBLIC."film"(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS PUBLIC."review_like" (
    review_id BIGINT NOT NULL REFERENCES PUBLIC."review"(review_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES PUBLIC."user"(id) ON DELETE CASCADE,
    is_positive BOOLEAN NOT NULL,
    PRIMARY KEY (review_id, user_id)
);
CREATE TABLE IF NOT EXISTS PUBLIC."user_feed" (
	event_id BIGINT NOT NULL AUTO_INCREMENT,
	entity_id BIGINT NOT NULL,
	user_id BIGINT NOT NULL,
	event_type varchar NOT NULL CHECK (event_type IN ('LIKE', 'REVIEW', 'FRIEND')),
	operation varchar NOT NULL CHECK (operation IN ('REMOVE', 'ADD', 'UPDATE')),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT USER_FEED_PK PRIMARY KEY (event_id)
);


